/**
 * What became of a CAD request, in the classes Fusion reads from WG's
 * request-status file. It reads the same job fields as
 * `server/cadlink/joblane/request_status.py::project_request_status` (the
 * job's status, then `cad_state.held`), so WG and Fusion cannot disagree
 * about a request. Both sides run the same table of states:
 * `server/tests/fixtures/cad_request_states.json` (regenerated by
 * `server/tests/cad_request_states_rows.py`).
 *
 * It drives the line's stage: a request still preparing, queued or solving
 * is busy and offers nothing (Stop stays in the run card), whatever kept
 * state it carries -- an update-restart hold is still preparing for Fusion;
 * a solved one offers its results. Questions, refusals and failures read
 * `currentModelStatus`'s classification, which works from the same job.
 */
export type CadRequestState = 'preparing' | 'queued' | 'solving' | 'solved' | 'cancelled' | 'needsYou' | 'couldNotFinish';

export function cadRequestState(job: Pick<JobItem, 'status' | 'cad_state'>): CadRequestState {
  switch (job.status) {
    case 'preparing': return 'preparing';
    case 'queued': return 'queued';
    case 'running': return 'solving';
    case 'complete': return 'solved';
    case 'cancelled': return 'cancelled';
    default: return isHeldCadJob(job) && !isFailedCadPreparation(job) ? 'needsYou' : 'couldNotFinish';
  }
}

/** The one action a status line offers. `prepare` stands until preparation is
 * automatic (it is the only Prepare left on screen); the rest are the plan's. */
export type CadStatusAction = 'solve' | 'choose' | 'try-again' | 'show-results' | 'prepare' | 'none';

export type CadStatusTone = 'idle' | 'busy' | 'ready' | 'attention' | 'done';

export interface CadModelStatusLine {
  /** The sentence the model card shows, once. */
  text: string;
  /** A few words for the status bar ("ready · 3,035 triangles"). */
  short: string;
  tone: CadStatusTone;
  action: CadStatusAction;
  /** The action's button label, or null for `none`. */
  actionLabel: string | null;
  /** The request a choose / try-again acts on; null for the browser's own preparation. */
  jobId: string | null;
}

export interface CadStatusContext {
  /** Results are on screen: a solved model needs no Show results. */
  resultsShown?: boolean;
  /** Solve waits for its engine (`SolveControl.waitingForEngine`). */
  waitingForEngine?: boolean;
  /** Where models come from when none is selected (the CAD app preference). */
  application?: string;
  /** The question's pop-up is open now: Choose… would only repeat it. */
  choiceOpen?: boolean;
}

type CadModelView = Pick<ReturnType<typeof selectCadModelState>,
  'selected' | 'label' | 'phase' | 'preparation' | 'heldRequest' | 'meshChoice' | 'failureMessage' | 'triangles' | 'canPrepare' | 'record' | 'bundle' | 'application'>
  & Partial<Pick<ReturnType<typeof selectCadModelState>, 'failureRetry'>>;

const ACTION_LABEL: Record<Exclude<CadStatusAction, 'none'>, string> = {
  solve: 'Solve', choose: 'Choose…', 'try-again': 'Try again', 'show-results': 'Show results', prepare: 'Prepare',
};

const ENGINE_HOLDS = new Set(['engine_unavailable', 'engine_cannot_solve_return']);

function line(text: string, short: string, tone: CadStatusTone, action: CadStatusAction = 'none', jobId: string | null = null,
  actionLabel: string | null = action === 'none' ? null : ACTION_LABEL[action]): CadModelStatusLine {
  return { text, short, tone, action, actionLabel, jobId };
}

/** How far a solve got, from the server's own count (`job.frequency_progress`)
 * when the job carries it; otherwise its overall fraction. */
function solving(job: JobItem): CadModelStatusLine {
  const frequency = job.frequency_progress;
  if (frequency && frequency.total > 0) {
    return line(`Solving · ${frequency.done} of ${frequency.total} frequencies`, `solving ${frequency.done}/${frequency.total}`, 'busy');
  }
  const percent = Math.round((job.progress ?? 0) * 100);
  return percent > 0 ? line(`Solving · ${percent}%`, `solving ${percent}%`, 'busy') : line('Solving…', 'solving…', 'busy');
}

/**
 * The selected CAD model's status, in one sentence with at most one action.
 * Every surface that states the model's state reads this: the model card
 * shows it once; the status bar uses `short`; the viewport says it when it has
 * nothing to draw; Results states it without the action.
 *
 * `request` is `currentModelStatus` for the model on screen, the same request
 * `selectCadModelState` was given.
 */
export function cadModelStatusLine(model: CadModelView, request: CadModelRequest | null, context: CadStatusContext = {}): CadModelStatusLine {
  const { label } = model;
  if (!model.selected) {
    return line(`No CAD model yet. In ${context.application ?? 'Fusion'}, use ${APP_NAME} ▸ Send or Solve.`, 'none selected', 'idle');
  }
  const job = request?.job ?? null;
  const requestState = job ? cadRequestState(job) : null;
  const state = job?.cad_state ?? null;
  const prepared = model.preparation === 'prepared';
  // The server's words with their one next step, as Fusion shows them.
  const serverWords = [state?.message, state?.next_step].filter(Boolean).join(' ') || request?.message || null;
  // A question for the user: the held request's pop-up, or the mesh-size
  // choice asked in this window. Choose… opens it, unless it is open.
  if (model.phase === 'waiting') {
    const reason = model.heldRequest?.cad_state?.reason ?? (model.meshChoice ? 'mesh_too_large' : null);
    const facts = meshCeilingFacts(model.heldRequest ?? model.meshChoice);
    const why = reason !== 'mesh_too_large' ? ' before it can be solved.'
      : facts ? `: it meshes to ${count(facts.triangles)} triangles (limit ${count(facts.limit)}).`
      : `: it is ${OPERATION_REASON_WORDS.mesh_too_large}.`;
    const open = context.choiceOpen || (!!model.meshChoice && !model.heldRequest && !model.meshChoice.deferred);
    return line(`${label} needs your choice${why}`, 'needs your choice', 'attention', open ? 'none' : 'choose', model.heldRequest?.id ?? null);
  }
  // WG prepares the model: in this window, or on the server for a request.
  // Either outranks a stale or missing mesh, which it is replacing. A job
  // still preparing is busy whatever it keeps (an update-restart hold
  // resumes by itself), as Fusion's status says.
  if (model.phase === 'preparing') return line(`Preparing ${label}…`, 'preparing…', 'busy');
  if (requestState === 'preparing') {
    if (request?.kind === 'refused' && state?.message) return line(state.message, 'preparing…', 'busy');
    return prepared ? line('Starting the solve…', 'starting…', 'busy') : line(`Preparing ${label}…`, 'preparing…', 'busy');
  }
  if (requestState === 'queued') return line(`${label} is queued to solve.`, 'queued', 'busy');
  if (requestState === 'solving' && job) return solving(job);
  // The engine gates: Results owns their details and remedies.
  if (context.waitingForEngine || (request?.kind === 'waiting' && state?.reason && ENGINE_HOLDS.has(state.reason))) {
    return state?.reason === 'engine_cannot_solve_return'
      ? line(`The selected engine cannot solve ${label}. Results says what to change.`, 'engine cannot solve it', 'attention')
      : line('Solve engine is getting ready…', 'engine getting ready…', 'busy');
  }
  // A failed preparation, in the server's words (one owner: the protocol's
  // could-not-prepare sentence, or what the user can change), with Try again
  // where the server offers it.
  if (request?.kind === 'prepare-failed' && job) {
    const retry = state?.options?.some(option => option.id === 'retry');
    return line(model.failureMessage || serverWords || couldNotPrepare(label), 'could not prepare', 'attention', retry ? 'try-again' : 'none', job.id);
  }
  if (model.preparation === 'prepare-failed') {
    const retry = model.canPrepare && model.failureRetry !== false;
    return line(model.failureMessage || couldNotPrepare(label), 'could not prepare', 'attention', retry ? 'try-again' : 'none');
  }
  // A refusal: its words. Solve again only where the server would take it
  // (a kept request that names a change WG settles with the settings on
  // screen); a rejected one is changed in Fusion or nowhere.
  if (request?.kind === 'refused' && job) {
    const solvable = prepared && state?.state === 'needs_user_input';
    return line(serverWords || `${APP_NAME} could not solve ${label}.`, 'not solved', 'attention', solvable ? 'solve' : 'none', job.id);
  }
  // Its mesh no longer matches the settings or the return: what was solved
  // or prepared before is not what Solve would use now.
  if (model.preparation === 'stale') {
    return line(`${label} changed since it was prepared.`, 'needs preparing again', 'attention',
      model.canPrepare ? 'prepare' : 'none', null, 'Prepare again');
  }
  if (requestState === 'solved' && request?.kind === 'solved' && job) {
    const run = job.run_number ? ` · run #${job.run_number}` : '';
    const when = job.completed_at ? ` · ${relativeTime(job.completed_at)}` : '';
    return line(`Solved${run}${when}`, 'solved', 'done', context.resultsShown ? 'none' : 'show-results', job.id);
  }
  if (request?.kind === 'failed' && job) {
    // WG's words when the server has some for the user; never the raw error.
    const words = state?.next_step ? serverWords : null;
    return line(words || `${APP_NAME} could not finish solving ${label}.`, 'could not finish', 'attention', 'try-again', job.id);
  }
  // A request kept until Solve: prepared, or naming a change (a frame changed
  // elsewhere). Solve continues it with what is on screen -- the server
  // prepares it first when WG has no mesh of it yet.
  if (request?.kind === 'waiting' && job) {
    if (state?.attention === 'ready') return ready(model);
    return line(serverWords || `${label} needs a change before it can be solved.`, 'needs a change', 'attention', 'solve', job.id);
  }
  if (model.phase === 'stopped') {
    return line(model.failureMessage || `${APP_NAME} could not solve ${label}.`, 'not solved', 'attention');
  }
  if (prepared) return ready(model);
  // A return WG cannot read, with no request preparing it: say so, and where
  // a readable copy comes from.
  if (model.bundle && !model.bundle.readable) {
    const app = model.application === 'CAD' ? context.application ?? 'Fusion' : model.application;
    return line(`${APP_NAME} cannot read ${label}. Send it again from ${app}.`, 'cannot read it', 'attention');
  }
  return line(`${label} is not prepared yet.`, 'not prepared', 'attention', model.canPrepare ? 'prepare' : 'none');
}

/** The browser's own failed preparation that the server did not classify as
 * WG's own (a refusal whose words the card's error notice says): the
 * protocol's could-not-prepare sentence without its "recorded" claim, which
 * only the server makes (`failure: "internal"`, then `failureMessage`). */
function couldNotPrepare(label: string): string {
  return `${APP_NAME} could not prepare ${label}.`;
}

function ready(model: CadModelView): CadModelStatusLine {
  const triangles = model.triangles === null ? '' : ` · ${model.triangles.toLocaleString()} triangles`;
  return line(`Ready to solve${triangles}`, `ready${triangles}`, 'ready', 'solve');
}

const count = (value: number) => value.toLocaleString();

/** The triangle ceiling's facts for a question about it: a held request's
 * (`cad_state.mesh_limit`) or the browser's own preparation's
 * (`meshCeilingChoice`). Never parsed from a message; null when the server did
 * not state them (a request held by an older build). */
export function meshCeilingFacts(source: Pick<JobItem, 'cad_state'> | Pick<MeshCeilingChoice, 'meshLimit'> | null | undefined): CadMeshLimit | null {
  if (!source) return null;
  const facts = 'meshLimit' in source ? source.meshLimit : (source as Pick<JobItem, 'cad_state'>).cad_state?.mesh_limit;
  return facts && facts.triangles > 0 && facts.limit > 0 ? facts : null;
}

/** The mesh-too-large pop-up's words: the facts, and what each option does.
 * `nextStep` is the server's own next step, for a question without facts. */
export function meshCeilingQuestion(name: string, facts: CadMeshLimit | null, nextStep: string, fusionRequest = false) {
  return {
    title: `${name} is larger than ${APP_NAME}'s limit`,
    body: facts
      ? `It meshes to ${count(facts.triangles)} triangles; ${APP_NAME}'s limit is ${count(facts.limit)}. Solving it anyway is slower and needs more memory.`
      : nextStep,
    /** "Change in Fusion": nothing in WG opens Fusion's dialog, so it says
     * where. A request from Fusion stays waiting, and Fusion's own panel
     * shows it with its Sources & Mesh… button. */
    changeInFusion: fusionRequest
      ? `In Fusion, the ${APP_NAME} panel shows this request with a Sources & Mesh… button. Raise Walls or add a coarser size zone there, then solve ${name} again from Fusion.`
      : `In Fusion, open ${APP_NAME} ▸ Sources & Mesh…, raise Walls or add a coarser size zone, then send ${name} again.`,
  };
}

/** The top-bar chip's words for requests waiting outside the model's own
 * status line. They follow the server's one classification: only a real
 * question waits for the user; anything else names a change to make, or WG's
 * own failed preparation. `otherModels`: a CAD model is on screen, so these
 * are about other models. */
export function cadRequestsChipLabel(
  waiting: ReadonlyArray<Pick<CadOperationSummary, 'kind' | 'attention'> | undefined>,
  { otherModels = false }: { otherModels?: boolean } = {},
): string {
  const first = waiting[0];
  if (waiting.length > 1) {
    return waiting.every(operation => operation?.kind === 'prepare_and_solve' && operation.attention === 'action')
      ? `${waiting.length} CAD requests need a change` : `${waiting.length} CAD requests need you`;
  }
  if (first?.kind !== 'prepare_and_solve') return 'A CAD update needs recovery';
  if (first.attention === 'question') return otherModels ? 'Another model needs your choice' : 'A solve is waiting for you';
  if (first.attention === 'action') return 'A solve needs a change';
  if (first.attention === 'failed') return 'A solve could not be prepared';
  return 'A solve is on hold';
}
