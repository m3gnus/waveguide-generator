def job(status: str, config: dict[str, Any], refusal: dict[str, Any] | None = None, **extra: Any) -> dict[str, Any]:
    cad: dict[str, Any] = {"operation_id": "req-1", "snapshot": SNAPSHOT}
    if refusal:
        cad["refusal"] = refusal
    row = {"id": "job-1", "status": status, "progress": 0.0, "run_number": None, "has_results": False,
           "stage": None, "stage_message": None, "error_message": None, "started_at": AT,
           "created_at": AT, "updated_at": AT, "completed_at": None,
           "config_json": config, "task_metadata": {"cad": cad}}
    row.update(extra)
    return row


def _held(code: str, message: str, **cad: Any) -> dict[str, Any]:
    row = job("held", INTENT, {"code": code, "message": message})
    row["task_metadata"]["cad"].update(cad)
    return row


