"""The shared table of CAD request states, and how to regenerate it.

``fixtures/cad_request_states.json`` is read by both sides of WGLink:
``test_cad_request_states.py`` projects each job into Fusion's request-status
file, and ``frontend/src/stores/cadModelStatusLine.test.ts`` classifies the
same jobs and checks WG's status line. Each row's ``cad_state`` is the
server's own read model of its job (``job_cad_state``), so it is generated,
never written by hand::

    python -m server.tests.cad_request_states_rows   # from the checkout root

``test_cad_request_states.py`` fails when the file and :func:`build` differ.
"""

