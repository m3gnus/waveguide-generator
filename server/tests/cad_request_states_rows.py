def build() -> dict[str, Any]:
    rows = []
    for name, model, row, state, action, text in ROWS:
        cad = job_cad_state(row)
        assert cad is not None
        kept = {key: cad[key] for key in _KEYS}
        words = text if text is not None else " ".join(str(part) for part in (cad["message"], cad["next_step"]) if part)
        rows.append({"name": name, "model": model, "job": {**row, "cad_state": kept}, "request_status": state,
                     "wg": {"action": action, "text": words}})
    return {"_comment": COMMENT, "rows": rows}


def write() -> None:
    FIXTURE.write_text(json.dumps(build(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write()
