#!/usr/bin/env python3
"""Generate a hashed installation lock while retaining plain constraints.

--write fetches distribution SHA256 hashes from PyPI for the exact versions in
requirements-lock.txt. --check is offline: it verifies the committed generated
file matches every constraint and has valid hash entries. Review hash updates
as supply-chain changes; checking does not refresh trust from the registry.
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import re
import sys
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "server" / "requirements-lock.txt"
HASHED = ROOT / "server" / "requirements-hashed.txt"
RUNTIME_HASHED = ROOT / "server" / "requirements-runtime-hashed.txt"
# These are exclusively the locked pytest toolchain, not runtime dependencies.
# pip check on the built runtime verifies that excluding them remains valid.
DEV_ONLY = {"pytest", "pytest-xdist", "execnet", "iniconfig", "pluggy"}
HEADER = "# Generated by scripts/hash_lock_requirements.py; do not edit.\n"
PIN = re.compile(r"^([A-Za-z0-9_.-]+)(?:\[[A-Za-z0-9_,.-]+\])?==([^;\s]+)(?:\s*;.*)?$")
DIGEST = re.compile(r"^[0-9a-f]{64}$")


def pins(text: str) -> list[str]:
    result = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not PIN.fullmatch(line):
            raise ValueError(f"Expected an exact distribution pin: {line!r}")
        if line in result:
            raise ValueError(f"Duplicate constraint: {line}")
        result.append(line)
    return result


def fetch_hashes(pin: str) -> tuple[str, list[str]]:
    match = PIN.fullmatch(pin)
    assert match is not None
    name, version = match.group(1, 2)
    request = Request(
        f"https://pypi.org/pypi/{name}/{version}/json",
        headers={"Accept": "application/json"},
    )
    with urlopen(request, timeout=30) as response:
        data = response.read(8 * 1024 * 1024 + 1)
    if len(data) > 8 * 1024 * 1024:
        raise ValueError(f"Registry metadata too large for {pin}")
    payload = json.loads(data)
    hashes = sorted({entry["digests"]["sha256"] for entry in payload["urls"]})
    if not hashes or any(not DIGEST.fullmatch(value) for value in hashes):
        raise ValueError(f"Registry has no valid distribution hashes for {pin}")
    return pin, hashes


def read_hashes(text: str) -> dict[str, list[str]]:
    result: dict[str, list[str]] = {}
    active: str | None = None
    for raw in text.splitlines():
        line = raw.strip().removesuffix("\\").rstrip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("--hash=sha256:"):
            digest = line.removeprefix("--hash=sha256:")
            if active is None or not DIGEST.fullmatch(digest):
                raise ValueError("Malformed or orphaned distribution hash")
            result[active].append(digest)
        else:
            if not PIN.fullmatch(line) or line in result:
                raise ValueError(f"Malformed or duplicate hashed pin: {line}")
            active = line
            result[active] = []
    return result


def render(lock: str, hashes: dict[str, list[str]]) -> str:
    expected = pins(lock)
    if set(hashes) != set(expected):
        raise ValueError("Hashed installation lock and plain constraints differ")
    output = [HEADER.rstrip()]
    for raw in lock.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            output.append(raw)
            continue
        values = hashes[line]
        if not values or any(not DIGEST.fullmatch(value) for value in values):
            raise ValueError(f"Missing or invalid hashes for {line}")
        output.append(raw + " \\")
        for index, value in enumerate(sorted(set(values))):
            suffix = " \\" if index < len(set(values)) - 1 else ""
            output.append(f"    --hash=sha256:{value}{suffix}")
    return "\n".join(output) + "\n"


def runtime_lock(lock: str) -> str:
    return "\n".join(
        raw for raw in lock.splitlines()
        if not (match := PIN.fullmatch(raw.strip()))
        or match.group(1).lower().replace("_", "-") not in DEV_ONLY
    ) + "\n"


def check(root: Path = ROOT) -> None:
    lock = (root / "server" / "requirements-lock.txt").read_text(encoding="utf-8")
    runtime_requirements = (root / "server" / "requirements-runtime.txt").read_text(encoding="utf-8")
    # Keep direct requirements authoritative too: installing only the hashed
    # closure must never silently ignore a version or platform-marker change.
    locked = {
        (PIN.fullmatch(pin).group(1).lower().replace("_", "-"), PIN.fullmatch(pin).group(2),
         pin.partition(";")[2].replace(" ", "")) for pin in pins(lock)
    }
    for pin in pins(runtime_requirements):
        match = PIN.fullmatch(pin)
        assert match is not None
        key = (match.group(1).lower().replace("_", "-"), match.group(2), pin.partition(";")[2].replace(" ", ""))
        if key not in locked:
            raise ValueError(f"Runtime requirement does not match the lock: {pin}")
    actual = (root / "server" / "requirements-hashed.txt").read_text(encoding="utf-8")
    hashes = read_hashes(actual)
    if actual != render(lock, hashes):
        raise ValueError("Hashed installation lock is stale; regenerate with --write")
    runtime = runtime_lock(lock)
    expected = render(runtime, {pin: hashes[pin] for pin in pins(runtime)})
    if (root / "server" / "requirements-runtime-hashed.txt").read_text(encoding="utf-8") != expected:
        raise ValueError("Hashed runtime lock is stale; regenerate with --write")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        lock = LOCK.read_text(encoding="utf-8")
        if args.write:
            with ThreadPoolExecutor(max_workers=8) as executor:
                hashes = dict(executor.map(fetch_hashes, pins(lock)))
            HASHED.write_text(render(lock, hashes), encoding="utf-8")
            runtime = runtime_lock(lock)
            RUNTIME_HASHED.write_text(render(runtime, {pin: hashes[pin] for pin in pins(runtime)}), encoding="utf-8")
        else:
            check()
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"Hash lock: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
